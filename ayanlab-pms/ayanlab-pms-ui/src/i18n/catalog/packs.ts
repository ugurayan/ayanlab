// Remaining locales: merge Spanish/English nav structure with localized UI via dedicated packs
function dashPack(
  title: string,
  customize: string,
  widgets: Record<string, string>,
  extra: Record<string, string> = {}
): MessageTree {
  return {
    title,
    customize,
    reset: extra.reset ?? "Reset to role default",
    view: extra.view ?? "View",
    roleLabel: extra.roleLabel ?? "Role",
    hiddenCount: extra.hiddenCount ?? "hidden",
    subtitleMock: extra.subtitleMock ?? "Role-based widgets (mock)",
    subtitleApi: extra.subtitleApi ?? "Role-based widgets (API)",
    patrolTonight: extra.patrolTonight ?? "Checkpoints tonight",
    eftPending: extra.eftPending ?? "EFT pending",
    vacant: extra.vacant ?? "Vacant",
    pendingApps: extra.pendingApps ?? "Pending apps",
    openViolations: extra.openViolations ?? "open violations",
    delinquent: extra.delinquent ?? "Delinquent",
    widgets,
    ...extra
  };
}

