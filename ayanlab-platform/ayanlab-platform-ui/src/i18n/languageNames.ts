export function sortedLocales(uiLocale: Locale): Locale[] {
  const labels = LANGUAGE_LABELS[uiLocale] ?? LANGUAGE_LABELS.en;
  return [...LOCALES].sort((a, b) =>
    labels[a].localeCompare(labels[b], uiLocale, { sensitivity: "base" }),
  );
}
