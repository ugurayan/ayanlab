#!/usr/bin/env python3
"""Sync locales/ayanlab-locales.json to platform UI, HRM backend seed, HRM UI, and mobile apps."""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "locales" / "ayanlab-locales.json"

MOBILE_APPS = [
    ROOT / "scripts/mobile-template/lib/core/state/app_state.dart",
    ROOT / "ayanlab-hrm/ayanlab-hrm-mobile/lib/core/state/app_state.dart",
    ROOT / "ayanlab-pms/ayanlab-pms-mobile/lib/core/state/app_state.dart",
    ROOT / "ayanlab-vault/ayanlab-vault-mobile/lib/core/state/app_state.dart",
    ROOT / "ayanlab-crm/ayanlab-crm-mobile/lib/core/state/app_state.dart",
    ROOT / "ayanlab-comm/ayanlab-comm-mobile/lib/core/state/app_state.dart",
    ROOT / "ayanlab-booking/ayanlab-booking-mobile/lib/core/state/app_state.dart",
]


def load_catalog():
    data = json.loads(CATALOG.read_text(encoding="utf-8"))
    locales = sorted(data["locales"], key=lambda x: x["sortOrder"])
    codes = [l["code"] for l in locales]
    if len(codes) != len(set(codes)):
        raise SystemExit("Duplicate locale codes in catalog")
    return locales, codes


def patch_navigation_seed(locales: list) -> None:
    path = ROOT / "ayanlab-hrm/ayanlab-hrm-backend/src/main/resources/db/staffiq-navigation-seed.json"
    root = json.loads(path.read_text(encoding="utf-8"))
    root["locales"] = [
        {
            "code": l["code"],
            "displayName": l["displayName"],
            "bcp47Tag": l["bcp47"],
            "sortOrder": l["sortOrder"],
            "enabled": True,
        }
        for l in locales
    ]
    path.write_text(json.dumps(root, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"updated {path.relative_to(ROOT)}")


def write_platform_locale_catalog(locales: list, codes: list[str]) -> None:
    codes_tuple = ", ".join(f'"{c}"' for c in codes)
    meta_lines = []
    for l in locales:
        if l.get("rtl"):
            meta_lines.append(f'  {l["code"]}: {{ rtl: true }},')
        else:
            meta_lines.append(f'  {l["code"]}: {{}},')
    entries_ts = ",\n".join(
        f"""  {{
    code: "{l['code']}",
    sortOrder: {l['sortOrder']},
    displayName: {json.dumps(l['displayName'])},
    nativeName: {json.dumps(l['nativeName'])},
    bcp47: {json.dumps(l['bcp47'])},
    rtl: {str(bool(l.get('rtl'))).lower()},
    trLabel: {json.dumps(l['trLabel'])},
  }}"""
        for l in locales
    )
    tr_map = ",\n".join(f'  {l["code"]}: {json.dumps(l["trLabel"])}' for l in locales)
    out = ROOT / "ayanlab-platform/ayanlab-platform-ui/src/i18n/localeCatalog.ts"
    content = f"""// Generated by scripts/sync-ayanlab-locales.py — do not edit by hand.

export const AYANLAB_LOCALE_ENTRIES = [
{entries_ts},
] as const;

export type AyanlabLocaleEntry = (typeof AYANLAB_LOCALE_ENTRIES)[number];

export const LOCALES = [{codes_tuple}] as const;
export type Locale = (typeof LOCALES)[number];

export const LOCALE_META: Record<Locale, {{ rtl?: boolean }}> = {{
{chr(10).join(meta_lines)}
}};

const TR_LABELS: Record<Locale, string> = {{
{tr_map}
}};

export function orderedLocales(): Locale[] {{
  return [...LOCALES];
}}

export function localeDisplayName(code: Locale, uiLocale: Locale): string {{
  const entry = AYANLAB_LOCALE_ENTRIES.find((l) => l.code === code);
  if (!entry) return code;
  if (uiLocale === code) return entry.nativeName;
  if (uiLocale === "tr") return TR_LABELS[code] ?? entry.displayName;
  return entry.displayName;
}}
"""
    out.write_text(content, encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")


def patch_platform_messages(codes: list[str]) -> None:
    path = ROOT / "ayanlab-platform/ayanlab-platform-ui/src/i18n/messages.ts"
    text = path.read_text(encoding="utf-8")
    text = re.sub(
        r"^export const LOCALES = \[.*?\] as const;\nexport type Locale = \(typeof LOCALES\)\[number\];\n\nexport const LOCALE_META: Record<Locale, \{ rtl\?: boolean \}> = \{[\s\S]*?\};\n",
        "",
        text,
        count=1,
        flags=re.MULTILINE,
    )
    if not text.startswith("import"):
        text = (
            'import { LOCALES, LOCALE_META, type Locale } from "./localeCatalog";\n\n'
            + text.lstrip()
        )
    elif "localeCatalog" not in text:
        text = text.replace(
            'type Dict = Record<string, string>;',
            'import { LOCALES, LOCALE_META, type Locale } from "./localeCatalog";\n\ntype Dict = Record<string, string>;',
            1,
        )
    # Ensure messages Record has stub for every locale
    for code in codes:
        if not re.search(rf"^\s{code}: \{{\s*\}},\s*$", text, re.MULTILINE):
            # insert before final `};` of messages export
            pass
    missing = []
    for code in codes:
        if not re.search(rf"^  {code}: ", text, re.MULTILINE):
            missing.append(code)
    if missing:
        stub = "\n".join(f"  {c}: {{}}," for c in missing)
        text = re.sub(r"(\n\};\s*)$", f"\n{stub}\n}};\n", text, count=1)
    path.write_text(text, encoding="utf-8")
    print(f"patched {path.relative_to(ROOT)} (+{len(missing)} message stubs)")


def write_language_names_shim() -> None:
    path = ROOT / "ayanlab-platform/ayanlab-platform-ui/src/i18n/languageNames.ts"
    path.write_text(
        """// Generated by scripts/sync-ayanlab-locales.py
import { type Locale, localeDisplayName, orderedLocales } from "./localeCatalog";

/** @deprecated use localeDisplayName + orderedLocales */
export function sortedLocales(_uiLocale: Locale): Locale[] {
  return orderedLocales();
}

export const LANGUAGE_LABELS: Record<Locale, Record<Locale, string>> = {} as Record<
  Locale,
  Record<Locale, string>
>;

export function languageLabel(code: Locale, uiLocale: Locale): string {
  return localeDisplayName(code, uiLocale);
}
""",
        encoding="utf-8",
    )


def patch_platform_preferences() -> None:
    path = ROOT / "ayanlab-platform/ayanlab-platform-ui/src/i18n/Preferences.tsx"
    text = path.read_text(encoding="utf-8")
    text = text.replace(
        'import { LANGUAGE_LABELS, sortedLocales } from "./languageNames";',
        'import { localeDisplayName, orderedLocales } from "./localeCatalog";',
    )
    text = text.replace(
        'import { LOCALES, LOCALE_META, messages, type Locale } from "./messages";',
        'import { LOCALES, LOCALE_META, type Locale } from "./localeCatalog";\nimport { messages } from "./messages";',
    )
    text = re.sub(
        r"\{sortedLocales\(locale\)\.map\(\(code\) => \(\s*<option key=\{code\} value=\{code\}>\s*\{LANGUAGE_LABELS\[locale\]\[code\]\}\s*</option>\s*\)\)\}",
        "{orderedLocales().map((code) => (\n          <option key={code} value={code}>\n            {localeDisplayName(code, locale)}\n          </option>\n        ))}",
        text,
        flags=re.DOTALL,
    )
    path.write_text(text, encoding="utf-8")


def patch_column_messages(codes: list[str]) -> None:
    path = ROOT / "ayanlab-platform/ayanlab-platform-ui/src/i18n/columnMessages.ts"
    text = path.read_text(encoding="utf-8")
    if 'from "./messages"' in text:
        text = text.replace(
            'import type { Locale } from "./messages";',
            'import type { Locale } from "./localeCatalog";',
        )
    missing = [c for c in codes if not re.search(rf"^  {c}: ", text, re.MULTILINE)]
    if not missing:
        return
    stubs = "\n".join(f"  {c}: {{ ...COL_EN }}," for c in missing)
    text = re.sub(r"\n\};\s*$", f"\n{stubs}\n}};\n", text, count=1)
    path.write_text(text, encoding="utf-8")


def write_hrm_ui_catalog(locales: list, codes: list[str]) -> None:
    entries_ts = ",\n".join(
        f"""  {{
    code: "{l['code']}",
    sortOrder: {l['sortOrder']},
    displayName: {json.dumps(l['displayName'])},
    nativeName: {json.dumps(l['nativeName'])},
    bcp47: {json.dumps(l['bcp47'])},
    rtl: {str(bool(l.get('rtl'))).lower()},
    trLabel: {json.dumps(l['trLabel'])},
  }}"""
        for l in locales
    )
    codes_union = " | ".join(f'"{c}"' for c in codes)
    out = ROOT / "ayanlab-hrm/ayanlab-hrm-ui/src/i18n/localeCatalog.ts"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        f"""// Generated by scripts/sync-ayanlab-locales.py — do not edit by hand.

export const AYANLAB_LOCALES = [
{entries_ts}
] as const;

export type LocaleCatalogEntry = (typeof AYANLAB_LOCALES)[number];

export type AppLanguage = {codes_union};

export const APP_LANGUAGE_CODES: AppLanguage[] = [
  {", ".join(f'"{c}"' for c in codes)}
];

export function isAppLanguage(value: string): value is AppLanguage {{
  return (APP_LANGUAGE_CODES as readonly string[]).includes(value);
}}

export function localeOptionLabel(code: AppLanguage, uiLanguage: AppLanguage): string {{
  const entry = AYANLAB_LOCALES.find((l) => l.code === code);
  if (!entry) return code;
  if (uiLanguage === "tr") return entry.trLabel;
  if (uiLanguage === code) return entry.nativeName;
  return entry.displayName;
}}

export const SPOKEN_LANGUAGE_OPTIONS = AYANLAB_LOCALES.map((l) => l.displayName);
""",
        encoding="utf-8",
    )
    print(f"wrote {out.relative_to(ROOT)}")


def patch_hrm_i18n() -> None:
    path = ROOT / "ayanlab-hrm/ayanlab-hrm-ui/src/state/i18n.tsx"
    path.write_text(
        """import React, { createContext, useContext, useEffect, useState } from "react";
import { type AppLanguage, APP_LANGUAGE_CODES, isAppLanguage } from "../i18n/localeCatalog";

export type Language = AppLanguage;

type I18nContextValue = {
  language: Language;
  setLanguage: (lang: Language) => void;
};

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

const STORAGE_KEY = "language";

function resolveInitialLanguage(): Language {
  if (typeof window === "undefined") {
    return "en";
  }
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored && isAppLanguage(stored)) {
    return stored;
  }
  return "en";
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => resolveInitialLanguage());

  useEffect(() => {
    if (typeof window === "undefined") {
      return;
    }
    window.localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  return (
    <I18nContext.Provider value={{ language, setLanguage }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error("useLanguage must be used within LanguageProvider");
  }
  return ctx;
}

/** UI copy bundles: only locales with full translations required; others fall back to English. */
export function useTranslations<T>(variants: Partial<Record<Language, T>> & { en: T }): T {
  const { language } = useLanguage();
  return variants[language] ?? variants.en;
}

export { APP_LANGUAGE_CODES };
""",
        encoding="utf-8",
    )


def patch_mobile_app_state(locales: list) -> None:
    tags = ", ".join(f"'{l['code']}'" for l in locales)
    displays = []
    for l in locales:
        native = l["nativeName"].replace("'", "\\'")
        name = l["displayName"].replace("'", "\\'")
        if native == name:
            displays.append(f"    '{l['code']}': '{name}',")
        else:
            displays.append(f"    '{l['code']}': '{native} ({name})',")
    block = f"""  static const supportedTags = <String>[
    {tags},
  ];

  static const displayNames = <String, String>{{
{chr(10).join(displays)}
  }};"""
    for path in MOBILE_APPS:
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        text = re.sub(
            r"  static const supportedTags = <String>\[[\s\S]*?\];\n\n  static const displayNames = <String, String>\{[\s\S]*?\};",
            block,
            text,
            count=1,
        )
        path.write_text(text, encoding="utf-8")
        print(f"updated {path.relative_to(ROOT)}")


def main() -> None:
    locales, codes = load_catalog()
    if len(codes) != 25:
        raise SystemExit(f"Expected 25 locales, got {len(codes)}")
    patch_navigation_seed(locales)
    write_platform_locale_catalog(locales, codes)
    write_language_names_shim()
    patch_platform_messages(codes)
    patch_platform_preferences()
    patch_column_messages(codes)
    write_hrm_ui_catalog(locales, codes)
    patch_hrm_i18n()
    patch_mobile_app_state(locales)
    patch_hrm_ui_screens()
    print("Done.")


def patch_hrm_ui_screens() -> None:
    shell = ROOT / "ayanlab-hrm/ayanlab-hrm-ui/src/ui/layout/AppShell.tsx"
    text = shell.read_text(encoding="utf-8")
    if "APP_LANGUAGE_CODES" not in text:
        text = text.replace(
            'import { Language, useLanguage, useTranslations } from "../../state/i18n";',
            'import { Language, useLanguage, useTranslations } from "../../state/i18n";\n'
            'import { localeOptionLabel } from "../../i18n/localeCatalog";',
        )
        text = re.sub(
            r"<select[\s\S]*?<option value=\"en\">EN</option>[\s\S]*?</select>",
            """<select
    value={language}
    onChange={(e) => setLanguage(e.target.value as Language)}
    className="bg-transparent text-xs font-medium text-slate-700 outline-none border-none focus:ring-0 max-w-[9rem]"
  >
    {APP_LANGUAGE_CODES.map((code) => (
      <option key={code} value={code}>
        {localeOptionLabel(code, language)}
      </option>
    ))}
  </select>""",
            text,
            count=1,
        )
        text = text.replace(
            'import { localeOptionLabel } from "../../i18n/localeCatalog";',
            'import { APP_LANGUAGE_CODES, localeOptionLabel } from "../../i18n/localeCatalog";',
        )
        shell.write_text(text, encoding="utf-8")

    settings = ROOT / "ayanlab-hrm/ayanlab-hrm-ui/src/views/settings/SettingsPage.tsx"
    if not settings.exists():
        return
    st = settings.read_text(encoding="utf-8")
    if "AYANLAB_LOCALES" not in st:
        st = st.replace(
            'import type { AccountSettings as AccountSettingsModel, LanguageLevel } from "../../types/settings";',
            'import type { AccountSettings as AccountSettingsModel, LanguageLevel } from "../../types/settings";\n'
            'import { AYANLAB_LOCALES } from "../../i18n/localeCatalog";',
        )
        old_opts = """              <option value="en">English</option>
              <option value="de">German</option>
              <option value="it">Italian</option>
              <option value="pl">Polish</option>
              <option value="tr">Turkish</option>"""
        if old_opts in st:
            new_opts = "\n".join(
                f'              <option value="{l["code"]}">{l["displayName"]}</option>'
                for l in sorted(
                    json.loads(CATALOG.read_text(encoding="utf-8"))["locales"],
                    key=lambda x: x["sortOrder"],
                )
            )
            st = st.replace(old_opts, new_opts)
        elif '<option value="en">English</option>' in st:
            pattern = (
                r'(<label className="text-xs font-semibold text-slate-600">Default language</label>\s*'
                r'<select[\s\S]*?value=\{language\}[\s\S]*?onChange=\{\(e\) => setLanguage\(e\.target\.value\)\}[\s\S]*?>)([\s\S]*?)(</select>)'
            )
            new_opts = "\n".join(
                f'              <option value="{l["code"]}">{l["displayName"]}</option>'
                for l in sorted(
                    json.loads(CATALOG.read_text(encoding="utf-8"))["locales"],
                    key=lambda x: x["sortOrder"],
                )
            )
            st = re.sub(pattern, rf"\1\n{new_opts}\n            \3", st, count=1)
        settings.write_text(st, encoding="utf-8")

    step4 = ROOT / "ayanlab-hrm/ayanlab-hrm-ui/src/views/jobs/wizard/Step4Requirements.tsx"
    s4 = step4.read_text(encoding="utf-8")
    if "SPOKEN_LANGUAGE_OPTIONS" not in s4:
        s4 = s4.replace(
            "const LANGUAGE_OPTIONS = ['English', 'German', 'French', 'Italian', 'Spanish', 'Polish'];",
            'import { SPOKEN_LANGUAGE_OPTIONS } from "../../../i18n/localeCatalog";\n\nconst LANGUAGE_OPTIONS = SPOKEN_LANGUAGE_OPTIONS;',
        )
        # fix duplicate import - move import to top
        if s4.count("import { SPOKEN_LANGUAGE_OPTIONS") > 1 or 'import { SPOKEN_LANGUAGE_OPTIONS' in s4.split("\n")[5]:
            lines = s4.splitlines()
            imp = 'import { SPOKEN_LANGUAGE_OPTIONS } from "../../../i18n/localeCatalog";'
            lines = [l for l in lines if "SPOKEN_LANGUAGE_OPTIONS" not in l or l.startswith("import")]
            if imp not in lines:
                insert = next(i for i, l in enumerate(lines) if l.startswith("import "))
                lines.insert(insert, imp)
            lines = [l for l in lines if l.strip() != "const LANGUAGE_OPTIONS = SPOKEN_LANGUAGE_OPTIONS;" or True]
            body = "\n".join(lines)
            body = body.replace(
                "const LANGUAGE_OPTIONS = ['English'",
                "const LANGUAGE_OPTIONS = SPOKEN_LANGUAGE_OPTIONS",
            )
            s4 = body
        step4.write_text(s4, encoding="utf-8")


if __name__ == "__main__":
    main()